"""Write the table of specs in spec/README.md, and the website's list and pages of them, from each spec's front matter.

uv run python scripts/spec_index.py           # rewrite them
uv run python scripts/spec_index.py --check   # fail if one is out of date (a pre-commit hook)
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec"
SITE = ROOT / "dashboard" / "lib" / "specs.json"
PAGES = ROOT / "dashboard" / "lib" / "spec-pages.ts"
START, END = "<!-- index:start -->", "<!-- index:end -->"
STATUS = {"done": "Done", "in-progress": "In progress", "planned": "Planned", "dropped": "Dropped"}
AREAS = [
    "Foundations",
    "Writing",
    "Reading",
    "Performance and scale",
    "Benchmarks",
    "Services and planned features",
]


def front_matter(path: Path) -> dict[str, str]:
    """The `key: value` lines between a spec's leading `---` lines."""
    text = path.read_text()
    match = re.match(r"---\n(.*?)\n---\n", text, re.DOTALL)
    if not match:
        sys.exit(f"{path.name}: no front matter")
    fields = dict(line.split(": ", 1) for line in match.group(1).splitlines())
    for key in ("number", "title", "area", "status", "updated"):
        if key not in fields:
            sys.exit(f"{path.name}: no `{key}` in the front matter")
    if fields["status"] not in STATUS:
        sys.exit(f"{path.name}: status must be one of {', '.join(STATUS)}, not {fields['status']!r}")
    if fields["area"] not in AREAS:
        sys.exit(f"{path.name}: area must be one of {', '.join(AREAS)}, not {fields['area']!r}")
    return fields


def specs() -> list[tuple[dict[str, str], str]]:
    """Every spec's front matter and file name, by number."""
    found = ((front_matter(p), p.name) for p in SPEC.glob("[0-9][0-9][0-9][0-9]-*.md"))
    return sorted(found, key=lambda s: int(s[0]["number"]))


def summary(name: str) -> str:
    """The spec's Summary section as one line."""
    match = re.search(r"^## Summary\n\n(.*?)\n\n## ", (SPEC / name).read_text(), re.DOTALL | re.MULTILINE)
    if not match:
        sys.exit(f"{name}: no Summary section")
    return " ".join(match.group(1).split())


def numbers(value: str | None) -> list[int]:
    """The numbers in a front-matter list such as `[3, 18]`."""
    return [int(n) for n in re.findall(r"\d+", value or "")]


def site_json() -> str:
    """The list the website renders, formatted as oxfmt would format it."""
    entries = []
    for fields, name in specs():
        entry = {
            "number": int(fields["number"]),
            "slug": name.removesuffix(".md"),
            "title": fields["title"],
            "area": fields["area"],
            "status": fields["status"],
            "updated": fields["updated"],
            "summary": summary(name),
            "related": numbers(fields.get("related")),
            "issues": numbers(fields.get("issues")),
        }
        lines = [f"    {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}" for k, v in entry.items()]
        entries.append("  {\n" + ",\n".join(lines) + "\n  }")
    return "[\n" + ",\n".join(entries) + "\n]\n"


def ts_key(name: str) -> str:
    """An object key as oxfmt writes it: quoted only where it must be."""
    return name if name.isidentifier() else f'"{name}"'


def pages_ts() -> str:
    """The website's imports of each spec's Markdown (and the landscape), rendered at build time."""
    names = [name.removesuffix(".md") for _, name in specs()] + ["landscape"]
    imports = "\n".join(f'  {ts_key(n)}: () => import("@spec/{n}.md"),' for n in names)
    return (
        "// Generated by scripts/spec_index.py: each spec's Markdown (`@spec/*` is ../spec), rendered at build time.\n"
        'import type { MDXContent } from "mdx/types"\n\n'
        "export const SPEC_PAGES: Record<string, () => Promise<{ default: MDXContent }>> = {\n"
        f"{imports}\n}}\n"
    )


def table() -> str:
    """The index: counts by status, then a table per area."""
    specs_ = specs()
    out = []
    for area in AREAS:
        out += [f"### {area}", "", "| # | Spec | Status | Updated |", "|---:|---|---|---|"]
        for fields, name in specs_:
            if fields["area"] == area:
                status = STATUS[fields["status"]]
                out.append(f"| {fields['number']} | [{fields['title']}]({name}) | {status} | {fields['updated']} |")
        out.append("")
    counts = {s: sum(f["status"] == s for f, _ in specs_) for s in STATUS}
    totals = ", ".join(f"{n} {STATUS[s].lower()}" for s, n in counts.items() if n)
    return f"{len(specs_)} specs: {totals}.\n\n" + "\n".join(out).rstrip() + "\n"


def main() -> None:
    """Rewrite the index and the website's list, or with `--check` fail if they are out of date."""
    readme = SPEC / "README.md"
    text = readme.read_text()
    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)
    updated = f"{before}{START}\n\n{table()}\n{END}{after}"
    outputs = {readme: updated, SITE: site_json(), PAGES: pages_ts()}
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, t in outputs.items() if not p.exists() or p.read_text() != t]
        if stale:
            sys.exit(f"{', '.join(stale)} out of date: uv run python scripts/spec_index.py")
        return
    for path, content in outputs.items():
        path.write_text(content)


if __name__ == "__main__":
    main()
